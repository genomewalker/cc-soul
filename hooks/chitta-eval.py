#!/usr/bin/env python3
"""chitta-eval — extended recall benchmark with confidence intervals.

Runs against hooks/chitta-eval-goldids.json (generated by scripts/gen-eval-queries.py).
Covers single-hop, multi-hop, temporal, and abstention query types.

Usage:
  hooks/chitta-eval.py                        # grade with hybrid strategy
  hooks/chitta-eval.py --strategy field       # grade with DAM field strategy
  hooks/chitta-eval.py --compare hybrid field # A/B compare two strategies
  hooks/chitta-eval.py --bootstrap            # re-verify gold IDs against live daemon
  hooks/chitta-eval.py --limit 20 --min 0.75 --quiet

Exit 0 if mean nDCG@limit >= --min, else 1.
"""
import argparse, json, math, os, random, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
GOLDIDS_PATH = ROOT / "hooks" / "chitta-eval-goldids.json"
G0_GOLDIDS_PATH = ROOT / "hooks" / "grade-recall-goldids.json"
RESULTS_PATH = ROOT / "hooks" / "chitta-eval-results.json"

_reranker = None
_RERANKER_MODEL = "cross-encoder/ms-marco-MiniLM-L-12-v2"
_RERANK_FETCH_MUL = 4


def _load_reranker():
    global _reranker
    if _reranker is not None:
        return _reranker
    try:
        import warnings
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            from sentence_transformers import CrossEncoder
            _reranker = CrossEncoder(_RERANKER_MODEL)
    except Exception:
        _reranker = False
    return _reranker


_RECALL_TIMEOUT_S = int(os.environ.get("CHITTA_EVAL_RECALL_TIMEOUT", "60"))


class RecallFailure(Exception):
    """Recall did not complete (timeout / crash / bad JSON). Distinct from an
    empty result set — a failure must NOT be scored as a zero-gold miss, or the
    metric measures harness load, not retrieval. See finding #5754223735221518410."""


def chitta_recall(query: str, limit: int, strategy: str, realm: str | None = None) -> list[dict]:
    cmd = ["chitta", "recall", "--query", query, "--limit", str(limit),
           "--strategy", strategy, "--json"]
    if realm:
        cmd += ["--realm", realm]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=_RECALL_TIMEOUT_S)
    except subprocess.TimeoutExpired as e:
        raise RecallFailure(f"timeout {_RECALL_TIMEOUT_S}s: {query[:60]!r}") from e
    if r.returncode != 0:
        raise RecallFailure(f"exit {r.returncode}: {query[:60]!r} :: {r.stderr[:120]}")
    if not r.stdout.strip():
        raise RecallFailure(f"empty stdout: {query[:60]!r}")
    try:
        return json.loads(r.stdout).get("results", [])
    except json.JSONDecodeError as e:
        raise RecallFailure(f"bad json: {query[:60]!r}") from e


def rerank(query: str, results: list[dict], limit: int) -> list[dict]:
    reranker = _load_reranker()
    if not reranker or len(results) <= limit:
        return results[:limit]
    pairs = [(query, r.get("text", "")) for r in results]
    scores = reranker.predict(pairs)
    ranked = sorted(zip(scores, results), key=lambda x: -float(x[0]))
    return [r for _, r in ranked[:limit]]


def ndcg(gold_ids: set, results: list[dict], limit: int) -> float:
    if not gold_ids:
        return 0.0
    dcg = 0.0
    for pos, r in enumerate(results[:limit]):
        if str(r.get("id", "")) in gold_ids:
            dcg += 1.0 / math.log2(pos + 2)
    idcg = sum(1.0 / math.log2(i + 2) for i in range(min(len(gold_ids), limit)))
    return dcg / idcg if idcg > 0 else 0.0


def bootstrap_ci(scores: list[float], n_boot: int = 1000, ci: float = 0.95) -> tuple[float, float]:
    if not scores:
        return 0.0, 0.0
    means = [sum(random.choices(scores, k=len(scores))) / len(scores) for _ in range(n_boot)]
    means.sort()
    lo = (1 - ci) / 2
    return means[int(lo * n_boot)], means[int((1 - lo) * n_boot) - 1]


def grade_strategy(queries: list[dict], strategy: str, limit: int,
                   use_reranker: bool, quiet: bool) -> dict:
    fetch_limit = limit * _RERANK_FETCH_MUL if use_reranker else limit
    scores_by_type: dict[str, list[float]] = {}
    per_query = []
    failed = []

    for q in queries:
        gold = set(q.get("gold_ids", []))
        qtype = q.get("type", "single_hop")
        realm = q.get("realm")

        try:
            results = chitta_recall(q["query"], fetch_limit, strategy, realm)
        except RecallFailure:
            try:  # one retry — recall is deterministic; a failure is load/timing, not signal
                results = chitta_recall(q["query"], fetch_limit, strategy, realm)
            except RecallFailure as e:
                failed.append(q["query"])
                print(f"\033[31m[FAIL-EXCLUDED]\033[0m {e}", file=sys.stderr)
                continue  # exclude from scoring — do NOT count a harness failure as a miss
        if use_reranker:
            results = rerank(q["query"], results, limit)
        else:
            results = results[:limit]

        # Gold IDs may include sig fallback: also check text match
        sig = q.get("gold_signature", "")
        if sig:
            for r in results:
                if sig in r.get("text", ""):
                    gold.add(str(r.get("id", "")))

        if qtype == "abstention":
            # Score = 1 if top result confidence < threshold, else 0
            # Proxy: if any result has id matching gold (empty set), nDCG=0 is correct
            score = 1.0  # abstention always "passes" since we have no gold
        else:
            score = ndcg(gold, results, limit)

        gold_pos = [i for i, r in enumerate(results[:limit]) if str(r.get("id","")) in gold]
        scores_by_type.setdefault(qtype, []).append(score)
        per_query.append({
            "query": q["query"], "type": qtype, "label": q.get("label", ""),
            "ndcg": round(score, 3), "gold_pos": gold_pos,
            "n_gold": len(gold), "n_results": len(results),
        })

        if not quiet:
            sig_mark = " \033[2m[sig]\033[0m" if sig and not gold_pos else ""
            color = "\033[32m" if score >= 0.7 else "\033[33m" if score >= 0.4 else "\033[31m"
            tag = "PASS" if score >= 0.7 else "WARN" if score >= 0.4 else "FAIL"
            if qtype == "abstention":
                tag, color = "ABS", "\033[36m"
            print(f"{color}[{tag}]\033[0m {q['query'][:50]:<52} nDCG={score:.3f}  "
                  f"pos={gold_pos}{sig_mark}")

    all_scores = [p["ndcg"] for p in per_query if p["type"] != "abstention"]
    mean = sum(all_scores) / len(all_scores) if all_scores else 0.0
    ci_lo, ci_hi = bootstrap_ci(all_scores)

    if failed:
        print(f"\033[33m[warn] {len(failed)} queries EXCLUDED (recall failed, not scored)\033[0m",
              file=sys.stderr)

    return {
        "strategy": strategy,
        "mean_ndcg": round(mean, 3),
        "ci_95": [round(ci_lo, 3), round(ci_hi, 3)],
        "n_queries": len(all_scores),
        "n_failed_excluded": len(failed),
        "by_type": {k: round(sum(v)/len(v), 3) for k, v in scores_by_type.items() if v},
        "per_query": per_query,
    }


def load_queries(path: Path) -> list[dict]:
    """Load from chitta-eval-goldids.json + merge G0 gold IDs."""
    data = json.loads(path.read_text()) if path.exists() else {"ids": {}, "meta": []}
    meta = data.get("meta", [])
    ids = data.get("ids", {})

    queries = []
    if meta:
        for m in meta:
            label = m.get("label", "")
            gold = ids.get(label, [])
            # Always seed gold with the original memory_id from generation time
            orig = m.get("memory_id")
            if orig and str(orig) not in [str(g) for g in gold]:
                gold = [str(orig)] + [str(g) for g in gold]
            queries.append({
                "query": m["query"],
                "label": label,
                "gold_ids": [str(g) for g in gold],
                "gold_signature": "",
                "type": m.get("type", "single_hop"),
                "realm": m.get("realm"),
            })
    else:
        # Fallback: use G0 format (version 3, plain dict of label→ids)
        for label, gold in ids.items():
            queries.append({
                "query": label.replace("_", " "),
                "label": label,
                "gold_ids": [str(g) for g in gold],
                "gold_signature": "",
                "type": "single_hop",
            })
    return queries


def load_g0_queries(path: Path) -> list[dict]:
    """Load G0 grade-recall-goldids.json (version 3 format with GOLDEN_SET)."""
    # Import golden set from grade-recall.py
    sys.path.insert(0, str(path.parent))
    try:
        import importlib.util
        spec = importlib.util.spec_from_file_location("grade_recall", path.parent / "grade-recall.py")
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        golden_set = mod.GOLDEN_SET
        ids_data = json.loads((path.parent / "grade-recall-goldids.json").read_text()).get("ids", {})
        queries = []
        for g in golden_set:
            label = g["desc"]
            gold = [str(x) for x in ids_data.get(label, [])]
            queries.append({
                "query": g["query"],
                "label": label,
                "gold_ids": gold,
                "gold_signature": g.get("gold_signature", ""),
                "type": "single_hop",
                "realm": "project:cc-soul",
            })
        return queries
    except Exception:
        return []


def bootstrap_goldids(queries: list[dict], limit: int, strategy: str) -> dict:
    """Re-verify gold IDs by running recall and checking signature/ID matches."""
    ids: dict = {}
    for q in queries:
        if q.get("type") == "abstention":
            ids[q["label"]] = []
            continue
        realm = q.get("realm")
        results = chitta_recall(q["query"], limit * _RERANK_FETCH_MUL, strategy, realm)
        retrieved = {str(r.get("id", "")) for r in results}
        sig = q.get("gold_signature", "")
        found = []
        # Sig-matched hits (durable across re-ingests)
        if sig:
            for r in results:
                if sig in r.get("text", ""):
                    found.append(str(r.get("id", "")))
        # Existing gold IDs that appear in results
        for g in q.get("gold_ids", []):
            if str(g) in retrieved and str(g) not in found:
                found.append(str(g))
        ids[q["label"]] = found
        print(f"  {q['label']}: {len(found)} gold IDs")
    return ids


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--strategy", default="hybrid",
                    help="Recall strategy: hybrid|semantic|field|smart (default: hybrid)")
    ap.add_argument("--compare", nargs="+", metavar="STRATEGY",
                    help="Compare multiple strategies side-by-side")
    ap.add_argument("--limit", type=int, default=20)
    ap.add_argument("--min", type=float, default=0.7)
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--no-reranker", action="store_true")
    ap.add_argument("--bootstrap", action="store_true",
                    help="Re-verify gold IDs against live daemon")
    ap.add_argument("--include-g0", action="store_true",
                    help="Include G0 (grade-recall.py) queries in eval")
    ap.add_argument("--out", default=str(RESULTS_PATH))
    ap.add_argument("--goldids", default=str(GOLDIDS_PATH),
                    help="Gold IDs file (default: hooks/chitta-eval-goldids.json)")
    args = ap.parse_args()

    goldids_path = Path(args.goldids)
    use_reranker = not args.no_reranker

    # Load queries
    queries = load_queries(goldids_path)
    if args.include_g0 or not queries:
        g0 = load_g0_queries(G0_GOLDIDS_PATH)
        seen = {q["label"] for q in queries}
        queries += [q for q in g0 if q["label"] not in seen]

    if not queries:
        print("No queries found. Run scripts/gen-eval-queries.py first.")
        sys.exit(1)

    if args.bootstrap:
        print(f"Bootstrapping {len(queries)} queries with strategy={args.strategy}...")
        ids = bootstrap_goldids(queries, args.limit, args.strategy)
        existing = json.loads(goldids_path.read_text()) if goldids_path.exists() else {}
        existing["ids"] = ids
        goldids_path.write_text(json.dumps(existing, indent=2))
        print(f"Updated gold IDs → {goldids_path}")
        return

    strategies = args.compare if args.compare else [args.strategy]
    results = {}

    for strat in strategies:
        if not args.quiet:
            print(f"\n\033[1mStrategy: {strat}\033[0m  (limit={args.limit}, reranker={use_reranker})")
            print("─" * 72)
        results[strat] = grade_strategy(queries, strat, args.limit, use_reranker, args.quiet)
        r = results[strat]
        print(f"\n\033[1m{'mean nDCG@' + str(args.limit)} = {r['mean_ndcg']:.3f}\033[0m"
              f"  95% CI [{r['ci_95'][0]:.3f}, {r['ci_95'][1]:.3f}]"
              f"  n={r['n_queries']}")
        for qtype, score in r.get("by_type", {}).items():
            print(f"  {qtype}: {score:.3f}")

    if len(strategies) > 1:
        print("\n\033[1mComparison:\033[0m")
        print(f"{'Strategy':<12} {'mean nDCG':<12} {'95% CI':<22} {'n'}")
        print("─" * 50)
        for s, r in results.items():
            ci = r["ci_95"]
            print(f"{s:<12} {r['mean_ndcg']:<12.3f} [{ci[0]:.3f}, {ci[1]:.3f}]      {r['n_queries']}")

    # Save results
    out_path = Path(args.out)
    out_path.write_text(json.dumps(results if len(strategies) > 1 else results[strategies[0]],
                                    indent=2))
    print(f"\nresult: {out_path}")

    mean = results[strategies[0]]["mean_ndcg"]
    sys.exit(0 if mean >= args.min else 1)


if __name__ == "__main__":
    main()
